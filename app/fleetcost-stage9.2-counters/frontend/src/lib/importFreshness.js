/** Свежесть данных источника импорта — «как давно загружали».
 *
 *  Вынесено из карточек страницы импорта по двум причинам:
 *    • правило «час / сутки» должно быть в одном месте, а не растекаться по
 *      разметке (раньше эти числа были вписаны прямо в условие вёрстки);
 *    • `now` передаётся параметром — пороги можно проверять без ожидания и без
 *      зависимости от текущего времени. В компоненте по умолчанию Date.now().
 *
 *  Смысл порогов: до часа данные считаем свежими, до суток — «нормально, но
 *  пора обновить», больше суток — «данных давно нет», и это проблема, потому что
 *  все суммы считаются по загруженным операциям.
 */

export const FRESH_HOURS = 1;
export const STALE_HOURS = 24;

/** Сколько часов прошло с момента загрузки. null — если её не было. */
export function hoursSince(iso, now = Date.now()) {
  if (!iso) return null;
  const t = new Date(iso).getTime();
  if (isNaN(t)) return null;
  return (now - t) / 3600000;
}

/** Цвет индикатора: зелёный — свежо, жёлтый — в пределах суток, красный — давно.
 *
 *  Ошибка — сразу красный, каким бы свежим ни был момент записи: история
 *  обновилась, но данные НЕ пришли, и зелёная точка на неудачной загрузке читалась
 *  бы как «всё хорошо». Так же трактуем «загрузки не было» — серый, а не зелёный.
 */
export function freshnessColor(last, now = Date.now()) {
  if (!last) return "var(--c-muted-2)";
  if (last.status === "failed") return "var(--c-danger)";
  const h = hoursSince(last.created_at, now);
  if (h === null) return "var(--c-muted-2)";
  if (h <= FRESH_HOURS) return "var(--c-emerald)";
  if (h <= STALE_HOURS) return "var(--c-warn-600)";
  return "var(--c-danger)";
}

/** То же словами: цвет не должен быть единственным носителем смысла
 *  (дальтонизм, скриншот в письме, печать). */
export function freshnessLabel(last, now = Date.now()) {
  if (!last) return "данные ещё не загружались";
  if (last.status === "failed") return "последняя загрузка завершилась ошибкой";
  const h = hoursSince(last.created_at, now);
  if (h === null) return "время последней загрузки неизвестно";
  if (h <= FRESH_HOURS) return "данные свежие: загружены меньше часа назад";
  if (h <= STALE_HOURS) return "данные загружены в течение суток";
  return `данные загружали ${Math.floor(h / 24)} дн. назад`;
}
