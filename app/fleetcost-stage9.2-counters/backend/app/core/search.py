"""Помощники для свободного поиска по текстовым полям.

Модуль намеренно не тянет ни FastAPI, ни SQLAlchemy: тогда его можно проверить
локально, без поднятого окружения и без установленных зависимостей бэкенда:

    python3 app/core/search.py
"""


def like_pattern(term: str) -> str:
    """Превращает пользовательский ввод в безопасный LIKE-шаблон.

    Спецсимволы LIKE обязаны быть экранированы:
      • `%` — «любые символы». Запрос «100%» без экранирования нашёл бы вообще
        все записи, а не те, где встречается «100%»;
      • `_` — «ровно один символ». Запрос «AB_CD» совпал бы и с «ABXCD».
    Обратный слэш экранируется ПЕРВЫМ, иначе он съел бы экранирование,
    добавленное для `%` и `_`.

    Возвращает шаблон для `ILIKE ... ESCAPE '\\'` — то есть ровно так, как его
    используют эндпоинты журнала действий.
    """
    escaped = term.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
    return f"%{escaped}%"


if __name__ == "__main__":  # pragma: no cover — самопроверка, запускается вручную
    cases = [
        # ввод                     ожидаемый шаблон                        что проверяем
        ("100%",                   "%100\\%%",                              "процент экранирован"),
        ("AB_CD",                  "%AB\\_CD%",                             "подчёркивание экранировано"),
        ("a\\b",                   "%a\\\\b%",                              "обратный слэш экранирован первым"),
        ("\\%",                    "%\\\\\\%%",                             "слэш не съедает экранирование процента"),
        ("192.168.65.1",           "%192.168.65.1%",                        "обычный ввод не меняется"),
        ("",                       "%%",                                    "пустой ввод"),
    ]
    failed = 0
    for value, expected, why in cases:
        got = like_pattern(value)
        ok = got == expected
        failed += 0 if ok else 1
        print(f"  {'✓' if ok else '✗'} like_pattern({value!r}) = {got!r}  — {why}")
        if not ok:
            print(f"      ожидалось: {expected!r}")
    print()
    print("✓ самопроверка пройдена" if not failed else f"✗ расхождений: {failed}")
    raise SystemExit(1 if failed else 0)
